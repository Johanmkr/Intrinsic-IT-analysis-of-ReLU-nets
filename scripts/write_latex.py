r"""LaTeX for the camera-ready manuscript, from results/summary/ (step 5).

Reads results/summary/ (written by summarize_results.py) and writes latex/:

  numbers.tex                    every entry of numbers.json as \res{<key>}
  tables/bias_by_rho_compact.tex main text: mean bias correction per ρ regime
  tables/bias_by_rho.tex         appendix: value, correction, seed-std and gap to H(Y)
  tables/heldout_vs_insample.tex appendix: held-out vs in-sample, deepest layer
  tables/baseline_sensitivity.tex appendix: Pearson r for every baseline setting
  tables/occupancy.tex           appendix: ρ and singleton fractions, Composite and WBC
  tables/occupancy_mnist.tex     appendix: ρ per MNIST architecture and PCA dimension
  tables/label_permutation.tex   appendix: clean vs label-permuted networks
  tables/ordering.tex            appendix: quotient spread over visiting orders, per ε

Copy latex/ into the manuscript next to figures/. The paper loads numbers.tex
in its preamble and writes a number as \res{fig2.r.binning8}; an unknown key
prints **??key** and a LaTeX warning. Tables are bare tabular environments
(booktabs) to \input inside the paper's own table float and caption.

Formatting: integers as they are, floats with three decimals. Keys that hold
a fraction (accuracy, *_frac, relative spread) also get a percent version
under <key>.pct, with one decimal and no % sign.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
SUMMARY = REPO / "results" / "summary"
OUT = REPO / "latex"

ESTIMATOR_NAMES = {
    "plug_in": "Plug-in",
    "miller_madow": "Miller--Madow",
    "grassberger": "Grassberger",
    "chao_shen": "Chao--Shen",
    "chao_wang_jost": "Chao--Wang--Jost",
    "ansb": "ANSB$^\\dagger$",
}
RHO_RANGES = {"rho<0.05": "$\\rho < 0.05$", "rho>0.3": "$\\rho > 0.3$", "rho>0.9": "$\\rho > 0.9$"}
DATASET_NAMES = {"composite": "Composite", "wbc": "WBC", "mnist": "MNIST"}
PERCENT_HINTS = ("accuracy", "_frac", "relative_spread")


def f3(x) -> str:
    """Three decimals; minus as in math mode. Missing values as an en dash."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.3f}".replace("-", "$-$")


def by_arch(df: pd.DataFrame) -> pd.DataFrame:
    """Rows ordered by width, then depth."""
    key = df["arch_str"].map(lambda a: (int(a.strip("[]").split(",")[0]), a.count(",")))
    return df.assign(_k=key).sort_values("_k", kind="stable").drop(columns="_k")


def arch(arch_str: str) -> str:
    return arch_str.replace(" ", "")


def write(name: str, text: str) -> None:
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"  {name}")


def tabular(colspec: str, header: list[str], rows: list[list[str]], groups: list[int] = ()) -> str:
    """A booktabs tabular; `groups` are row indices that get a \\midrule above them."""
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for i, row in enumerate(rows):
        if i in groups:
            lines.append("\\midrule")
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "% Generated by scripts/write_latex.py from results/summary/; do not edit.\n" + "\n".join(lines)


