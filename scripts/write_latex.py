def bias_by_rho() -> None:
    df = pd.read_csv(SUMMARY / "bias_corrections_by_rho.csv").set_index(["rho_range", "estimator"])
    n = {r: int(df.loc[(r, "plug_in"), "n_cells"]) for r in RHO_RANGES}

    # Main text: mean correction (plug-in − corrected), one column per ρ regime
    header = ["Estimator"] + [f"{lab} ($n={n[r]}$)" for r, lab in RHO_RANGES.items()]
    rows = [[ESTIMATOR_NAMES[e]] + [f3(df.loc[(r, e), "mean_correction"]) for r in RHO_RANGES]
            for e in ESTIMATOR_NAMES if e != "plug_in"]
    write("tables/bias_by_rho_compact.tex", tabular("l" + "r" * len(RHO_RANGES), header, rows))

    # Appendix: every statistic, one block per ρ regime
    header = ["$\\rho$ range", "Estimator", "Value", "Correction", "Seed std", "Gap to $H(Y)$"]
    rows, groups = [], []
    for r, lab in RHO_RANGES.items():
        if rows:
            groups.append(len(rows))
        for e in ESTIMATOR_NAMES:
            s = df.loc[(r, e)]
            rows.append([f"{lab} ($n={n[r]}$)" if e == "plug_in" else "", ESTIMATOR_NAMES[e],
                         f3(s["mean_value"]), f3(s["mean_correction"]),
                         f3(s["mean_seed_std"]), f3(s["mean_gap_to_H_Y"])])
    write("tables/bias_by_rho.tex", tabular("llrrrr", header, rows, groups))


def heldout_vs_insample() -> None:
    df = pd.read_csv(SUMMARY / "heldout_vs_insample.csv")
    df = df[df["layer"] == df["arch_str"].str.count(",") + 1]           # deepest layer
    header = ["Dataset", "Architecture", "$\\rho$ held-out", "$\\rho$ in-sample",
              "$\\hat I$ held-out", "$\\hat I$ in-sample", "$\\Delta \\hat I$"]
    rows, groups = [], []
    for ds, sub in by_arch(df).groupby("dataset", sort=False):
        if rows:
            groups.append(len(rows))
        for i, (_, s) in enumerate(sub.iterrows()):
            rows.append([DATASET_NAMES[ds] if i == 0 else "",
                         f"$[{arch(s.arch_str)[1:-1]}]$", f3(s.rho_heldout), f3(s.rho_insample),
                         f3(s.plug_in_bits_heldout), f3(s.plug_in_bits_insample), f3(s.delta_plug_in)])
    write("tables/heldout_vs_insample.tex", tabular("llrrrrr", header, rows, groups))


def baseline_sensitivity() -> None:
    df = pd.read_csv(SUMMARY / "baseline_sensitivity.csv")
    est = df["estimator"].map(lambda e: "ksg" if e.startswith("ksg") else e)
    wide = df.assign(estimator=est).pivot_table(index=["family", "setting"], columns=["group", "estimator"],
                                                values="pearson_r", sort=False)
    submitted = set(df.loc[df["submitted"], "setting"])
    header = ["Baseline", "Setting",
              "\\multicolumn{2}{c}{Composite + WBC ($n=60$)}", "\\multicolumn{2}{c}{MNIST FC ($n=15$)}"]
    sub = ["", "", "plug-in", "MM", "plug-in", "MM"]
    rows, groups, last = [], [], None
    for (family, setting), s in wide.iterrows():
        if family != last and last is not None:
            groups.append(len(rows))
        label = setting.removeprefix(family) + ("$^*$" if setting in submitted else "")
        if family == "ksg":
            vals = [f3(s[("composite+wbc", "ksg")]), "", f3(s[("mnist", "ksg")]), ""]
        else:
            vals = [f3(s[(g, e)]) for g in ("composite+wbc", "mnist") for e in ("plug_in", "miller_madow")]
        rows.append([{"binning": "Binning ($K$)", "kmeans": "$k$-means ($K$)", "ksg": "KSG ($k$)"}[family]
                     if family != last else "", label] + vals)
        last = family
    text = tabular("llrrrr", header, rows, groups)
    first = " & ".join(header) + " \\\\\n"
    text = text.replace(first + "\\midrule", first + "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n"
                        + " & ".join(sub) + " \\\\\n\\midrule")
    write("tables/baseline_sensitivity.tex", text)


def occupancy() -> None:
    df = pd.read_csv(SUMMARY / "occupancy.csv")
    df = df[df["protocol"] == "heldout"]
    cw = df[df["dataset"] != "mnist"]
    header = ["Dataset", "Architecture", "Regions", "$\\rho$", "Singleton regions", "Singleton samples"]
    rows, groups = [], []
    for ds, sub in by_arch(cw).groupby("dataset", sort=False):
        if rows:
            groups.append(len(rows))
        for i, (_, s) in enumerate(sub.iterrows()):
            rows.append([DATASET_NAMES[ds] if i == 0 else "",
                         f"$[{arch(s.arch_str)[1:-1]}]$", f"{s.num_regions:.1f}", f3(s.rho),
                         f3(s.singleton_region_frac), f3(s.singleton_sample_frac)])
    write("tables/occupancy.tex", tabular("llrrrr", header, rows, groups))

    mn = df[df["dataset"] == "mnist"].pivot_table(index="arch_str", columns="target_dim", values="rho", sort=False)
    mn = mn.loc[sorted(mn.index, key=lambda a: int(a.strip("[]").split(",")[0]))]
    header = ["Architecture"] + [f"$d = {d}$" for d in mn.columns]
    rows = [[f"$[{arch(a)[1:-1]}]$"] + [f3(v) for v in s] for a, s in mn.iterrows()]
    write("tables/occupancy_mnist.tex", tabular("l" + "r" * len(mn.columns), header, rows))


def label_permutation() -> None:
    df = pd.read_csv(SUMMARY / "label_permutation.csv")
    test = df[(df["protocol"] == "heldout") & (df["labels"] == "true_labels")]
    fit = df[(df["protocol"] == "train") & (df["labels"] == "train_labels")].set_index(["dataset", "arch_str"])
    header = ["Dataset", "Architecture", "Labels", "Test acc.", "Train-label acc.", "$\\rho$",
              "$\\hat I$", "$\\hat I_{\\mathrm{func}}$", "$\\rho_{\\mathrm{func}}$"]
    rows, groups = [], []
    for ds, sub in test.groupby("dataset", sort=False):
        if rows:
            groups.append(len(rows))
        sub = by_arch(sub.sort_values("condition"))
        for i, (_, s) in enumerate(sub.iterrows()):
            train_acc = fit.loc[(ds, s.arch_str), "accuracy"] if s.condition == "permuted" else None
            rows.append([DATASET_NAMES[ds] if i == 0 else "",
                         f"$[{arch(s.arch_str)[1:-1]}]$", s.condition,
                         f"{100 * s.accuracy:.1f}\\%",
                         "--" if train_acc is None else f"{100 * train_acc:.1f}\\%",
                         f3(s.rho), f3(s.plug_in_bits), f3(s.plug_in_func_bits), f3(s.rho_func)])
    write("tables/label_permutation.tex", tabular("lllrrrrrr", header, rows, groups))


def ordering() -> None:
    df = pd.read_csv(SUMMARY / "ordering_by_epsilon.csv")
    header = ["Layers", "$\\varepsilon$", "Cells", "Median", "95th pct.", "Max", "Max / $R$",
              "Max $\\Delta \\hat I^{\\mathrm{MM}}_{\\mathrm{func}}$"]
    rows, groups = [], []
    for scope, sub in df.groupby("scope", sort=False):
        if rows:
            groups.append(len(rows))
        for i, (_, s) in enumerate(sub.iterrows()):
            rows.append([scope if i == 0 else "", f"{s.epsilon:g}", str(int(s.n_cells)),
                         f"{s.spread_median:g}", f"{s.spread_p95:.1f}", str(int(s.spread_max)),
                         f"{100 * s.relative_spread_max:.1f}\\%", f3(s.miller_madow_func_spread_max)])
    write("tables/ordering.tex", tabular("lrrrrrrr", header, rows, groups))


def main() -> None:
    print("Writing latex/:")
    numbers_tex()
    bias_by_rho()
    heldout_vs_insample()
    baseline_sensitivity()
    occupancy()
    label_permutation()
    ordering()


if __name__ == "__main__":
    main()
