# numbers.tex
# ---------------------------------------------------------------------------
def tex_value(value) -> str:
    if isinstance(value, bool) or isinstance(value, str):
        return str(value).replace("_", "\\_")
    if isinstance(value, int) or (isinstance(value, float) and value.is_integer() and abs(value) >= 1):
        return f"{int(value):,}".replace(",", "{,}")
    return f3(value).replace("$-$", "-")   # \res is used in math mode as well as text


def numbers_tex() -> None:
    numbers = json.loads((SUMMARY / "numbers.json").read_text())
    lines = [
        "% Generated by scripts/write_latex.py from results/summary/numbers.json; do not edit.",
        "% Usage: \\res{<key>}, e.g. $r = \\res{fig2.r.binning8}$; keys are listed in SUMMARY.md.",
        "\\makeatletter",
        "\\newcommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname"
        "\\else\\PackageWarning{numbers}{Unknown result key `#1'}\\textbf{??\\detokenize{#1}}\\fi}",
        "\\newcommand{\\defres}[2]{\\expandafter\\def\\csname res@#1\\endcsname{#2}}",
        "\\makeatother",
    ]
    for key, value in numbers.items():
        lines.append(f"\\defres{{{key}}}{{{tex_value(value)}}}")
        if isinstance(value, float) and any(h in key for h in PERCENT_HINTS):
            lines.append(f"\\defres{{{key}.pct}}{{{100 * value:.1f}}}")
    write("numbers.tex", "\n".join(lines) + "\n")


